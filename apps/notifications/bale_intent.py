"""نیّتِ اتصال — پلِ «یک ضربه» بینِ سایت و رباتِ بله، بدونِ هیچ مکالمه‌ای.

── مسئله ───────────────────────────────────────────────────────────────────
کاربر نباید در بله چیزی تایپ کند. حتی فرستادنِ کدِ ۶ کاراکتری هم یک مکالمه
است. ولی بله برای اینکه بتوانیم برای کسی پیام بفرستیم، باید `chat_id` او را
بدانیم و آن را فقط وقتی می‌دهد که خودِ کاربر با ربات تعامل کرده باشد.

── راه‌حل: دو کارِ استاندارد، صفر تایپ ─────────────────────────────────────
۱) **پیوندِ عمیق با پارامتر:** سایت یک توکنِ یک‌بارمصرف می‌سازد و کاربر را به
   `https://ble.ir/<bot>?start=<token>` می‌فرستد. بله همان لحظه
   «`/start <token>`» را به ربات می‌دهد ⇒ ما `chat_id` را می‌گیریم. کاربر
   **هیچ‌چیز** تایپ نکرده است.

۲) **دکمهٔ «ارسالِ شمارهٔ من»:** اگر بله پارامترِ `start` را منتقل نکند، تنها
   راهِ قابلِ اعتماد، پیامِ `contact`ِ خودِ بله است (نه تایپِ شماره). سایت
   دکمه‌ای نشان می‌دهد که چتِ ربات را با همان دکمهٔ اشتراکِ شماره باز می‌کند و
   کاربر یک ضربه می‌زند.

── چرا توکن و نه خودِ شماره در پیوند؟ ─────────────────────────────────────
اگر شماره در نشانی می‌رفت، در تاریخچهٔ مرورگر، لاگِ پروکسی و اسکرین‌شات‌ها
می‌ماند. توکنِ کوتاه (۶ کاراکتر، ۲۰ دقیقه، فقط هش در دیتابیس) چیزی لو نمی‌دهد
و مثلِ کدِ اتصالِ قبلی ولی **بی‌نیاز از تایپ** کار می‌کند.
"""

from __future__ import annotations

import secrets
from typing import Any
from urllib.parse import urlencode

from django.conf import settings


def bot_username() -> str:
    """نامِ کاربریِ ربات: تنظیمات، وگرنه از خودِ بله (بدونِ @)."""
    configured = str(getattr(settings, "BALE_BOT_USERNAME", "") or "").strip().lstrip("@")
    if configured:
        return configured
    try:
        from apps.notifications.bale import get_me

        return str(get_me().get("username") or "").lstrip("@")
    except Exception:
        return ""


def bot_deep_link(token: str = "") -> str:
    """پیوندِ عمیقِ ربات؛ با `?start=` بله خودش پیامِ شروع را می‌فرستد."""
    name = bot_username()
    if not name:
        return ""
    base = f"https://ble.ir/{name}"
    return f"{base}?{urlencode({'start': token})}" if token else base


def share_contact_link(token: str = "") -> str:
    """پیوندی که گفتگو را با دکمهٔ «ارسالِ شمارهٔ من» باز می‌کند.

    بله (مانندِ تلگرام) پارامترِ `?start=` و `?text=` را در پیوندِ ربات
    پشتیبانی می‌کند؛ اگر `text` را بدهیم، در کادرِ نوشتن پیش‌نویس می‌شود و
    کاربر فقط «ارسال» را می‌زند. این بهترین چیزی است که بدونِ تعاملِ سرور در
    بله می‌شود ساخت — و اگر بله آن را نادیده گرفت، خودِ ربات دکمهٔ اشتراکِ
    شماره را می‌فرستد (پیامِ اول پس از «شروع»).
    """
    name = bot_username()
    if not name:
        return ""
    return f"https://ble.ir/{name}?{urlencode({'text': '/start'})}"


def contact_request_keyboard() -> dict[str, Any]:
    """کیبوردِ «ارسالِ شمارهٔ من» — تنها تعاملِ لازم، یک ضربه.

    چرا `request_contact`؟ شماره‌ای که کاربر تایپ می‌کند همیشه منبعِ خطاست
    (رقمِ فارسی، ۰ و ۵ جابه‌جا، ۰۹ نشده) و هم قابلِ جعل است. شماره‌ای که بله
    با دکمهٔ رسمی می‌فرستد، به حسابِ خودِ کاربر گره خورده و ما می‌توانیم به آن
    اعتماد کنیم — یعنی همان چیزی که مقصودِ «کدِ ورود از راهِ بله» است.
    """
    return {
        "keyboard": [
            [{"text": "📱 ارسالِ شمارهٔ من", "request_contact": True}],
        ],
        "resize_keyboard": True,
        "one_time_keyboard": True,
    }


def new_intent_token() -> str:
    """توکنِ کوتاهِ یک‌بارمصرف (۶ کاراکترِ بزرگ، بدونِ حروفِ گیج‌کننده)."""
    alphabet = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"
    return "".join(secrets.choice(alphabet) for _ in range(6))
